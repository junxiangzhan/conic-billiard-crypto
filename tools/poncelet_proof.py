"""Computer-algebra proofs for the Poncelet-pencil construction.

Requires sympy (uv dependency group "tools"):

    uv run --group tools python tools/poncelet_proof.py

Every check is an exact identity.  Rational expressions are cleared of
denominators and the numerator is reduced modulo the curve ideal; a zero
remainder proves the identity on the curve.  The ideal is generated by
c_i^2 + eps*s_i^2 - 1 and d_i^2 + m*s_i^2 - 1; their leading monomials c_i^2,
d_i^2 are pairwise coprime, so they form a Groebner basis (Buchberger's first
criterion).  Every generator is monic in c_i or d_i, so the division never
divides by an integer: an identity found over Q holds over Z, hence over every
F_p with p odd, wherever the cleared denominators are non-zero
(see docs/proofs.md for the list).

Model, eps = +1 (ellipse) or eps = -1 (hyperbola):
  boundary    E : x^2/A + y^2/B = 1,           A = a^2,  B = eps*b^2
  caustic     C : x^2/(A-lam) + y^2/(B-lam) = 1
  pencil      C_mu : E + mu*C                   (z^2-coefficient -1 in both)
  state curve J : c^2 + eps*s^2 = 1,  d^2 + m*s^2 = 1,   m = eps*(B-A)/(B-lam)
  projection  pi(s,c,d) = (a*c, b*s);  identity O = (0,1,1);  T = (0,1,-1)
  addition    (s1,c1,d1)+(s2,c2,d2) = ((s1c2d2+s2c1d1), (c1c2-eps*s1s2d1d2),
              (d1d2-m*s1s2c1c2)) / (1-eps*m*s1^2 s2^2)
              (for eps=+1 this is conic_billiard/jacobi.py; for eps=-1 it is the
              same law after s -> i*s, m -> -m)
"""
from __future__ import annotations

import sys
import time

from sympy import (Poly, cancel, expand, factor, fraction, reduced, symbols,
                   together)

a, b, m, mu, t, t1, t2 = symbols('a b m mu t t1 t2')
s, c, d = symbols('s c d')
s1, c1, d1, s2, c2, d2 = symbols('s1 c1 d1 s2 c2 d2')
FAILED: list[str] = []
T0 = time.time()


def check(name: str, ok: bool) -> None:
    print(f'  [{"ok" if ok else "FAIL"}] {name}   ({time.time() - T0:.1f}s)', flush=True)
    if not ok:
        FAILED.append(name)


def zero_mod(expr, ideal, gens) -> bool:
    """True iff the numerator of expr lies in the ideal (Groebner reduction)."""
    num = expand(fraction(together(expr))[0])
    return num == 0 or expand(reduced(num, ideal, *gens, order='lex')[1]) == 0


def line_through(X, Y):
    return (X[1] - Y[1], Y[0] - X[0], X[0] * Y[1] - Y[0] * X[1])


def run(eps: int) -> None:
    print(f'\n=== eps = {eps:+d} ({"ellipse" if eps == 1 else "hyperbola"}) ===', flush=True)
    A, B = a ** 2, eps * b ** 2
    lam = B - eps * (B - A) / m                     # <=> m = eps*(B-A)/(B-lam)
    e = (1 / A, 1 / B, -1)
    cv = (1 / (A - lam), 1 / (B - lam), -1)
    J1 = [c ** 2 + eps * s ** 2 - 1, d ** 2 + m * s ** 2 - 1]
    J2 = [c1 ** 2 + eps * s1 ** 2 - 1, d1 ** 2 + m * s1 ** 2 - 1,
          c2 ** 2 + eps * s2 ** 2 - 1, d2 ** 2 + m * s2 ** 2 - 1]
    red_s = lambda z: expand(expand(z).subs(s ** 2, (1 - c ** 2) / eps))   # s^2 -> (1-c^2)/eps

    def tangency(line):
        q = [e[i] + mu * cv[i] for i in range(3)]
        F = line[0] ** 2 * q[1] * q[2] + line[1] ** 2 * q[0] * q[2] + line[2] ** 2 * q[0] * q[1]
        return Poly(fraction(together(expand(F)))[0], mu).all_coeffs()

    # L0  reflection at X1 of the ray X0->X1 is the other tangent from X1 to the caustic of chord X0X1
    P = lambda u: (a * (1 - eps * u ** 2) / (1 + eps * u ** 2), 2 * b * u / (1 + eps * u ** 2))
    X0, X1 = P(t1), P(t2)
    u_, v_, w_ = X1[1] - X0[1], X0[0] - X1[0], X0[0] * X1[1] - X0[1] * X1[0]
    lc = (A * u_ ** 2 + B * v_ ** 2 - w_ ** 2) / (u_ ** 2 + v_ ** 2)
    vx, vy = X1[0] - X0[0], X1[1] - X0[1]
    nx, ny = X1[0] / A, X1[1] / B
    k = 2 * (vx * nx + vy * ny) / (nx ** 2 + ny ** 2)
    wx, wy = vx - k * nx, vy - k * ny
    l0, l1, l2 = -wy, wx, X1[0] * wy - X1[1] * wx
    check('L0  reflection = the other tangent to the confocal caustic',
          expand(fraction(together((A - lc) * l0 ** 2 + (B - lc) * l1 ** 2 - l2 ** 2))[0]) == 0)

    # L10 the single-step formula: the pencil step with mu = infinity uses the direction
    #     d = (Cf*y1, Af*x1) (Vieta's other root of the tangent-direction quadratic).  It is
    #     parallel to the reflected direction w, and both formulas take the second
    #     intersection with E by the same scale-invariant t = -2 X^T E v / v^T E v, so the
    #     pencil step at mu = infinity IS the reflection map.
    qC = (1 / (A - lc), 1 / (B - lc), -1)

    def form(dv):
        xqd = qC[0] * X1[0] * dv[0] + qC[1] * X1[1] * dv[1]
        xqx = qC[0] * X1[0] ** 2 + qC[1] * X1[1] ** 2 + qC[2]
        dqd = qC[0] * dv[0] ** 2 + qC[1] * dv[1] ** 2
        return xqd ** 2 - xqx * dqd
    Af, Cf = form((1, 0)), form((0, 1))
    dv = (Cf * (X0[1] - X1[1]), Af * (X0[0] - X1[0]))
    check('L10 pencil step at mu = infinity has the reflected direction (so it is the reflection)',
          expand(fraction(together(wx * dv[1] - wy * dv[0]))[0]) == 0)

    # L1  chord pi(O) pi(W): discriminant = (R d)^2 on J, so both roots are rational in (c, d)
    A2, B1, C0 = [red_s(z) for z in tangency(line_through((a, 0), (a * c, b * s)))]
    R = 2 * (A - B) ** 3 * (c - 1) * (m - eps) * (a ** 2 + b ** 2 * (m - eps))
    check('L1  discriminant of chord O->W equals (R*d)^2 on J',
          zero_mod(B1 ** 2 - 4 * A2 * C0 - (R * d) ** 2, J1, (c, d, s)))

    # L2  closed form of mu(W)
    K = a ** 2 + b ** 2 * (m - eps)
    N = -(A - B) * (m - eps) * (c - 1)
    D = a ** 2 * m * (c - 1) + eps * K * (1 + d)
    muW = N / D
    print(f'      mu(W) = {factor(muW)}', flush=True)
    check('L2  mu(W) = -(A-B)(m-eps)(c-1) / (a^2 m (c-1) + eps K (1+d)) is a root of chord O->W',
          zero_mod(A2 * N ** 2 + B1 * N * D + C0 * D ** 2, J1, (c, d, s)))
    check('L2  it is the root (-B1 - eps*R*d)/(2*A2)',
          zero_mod(muW - (-B1 - eps * R * d) / (2 * A2), J1, (c, d, s)))
    Nf, Df = N.subs(d, -d), D.subs(d, -d)
    check('L2  the other root is mu evaluated at (s, c, -d)',
          zero_mod(A2 * Nf ** 2 + B1 * Nf * Df + C0 * Df ** 2, J1, (c, d, s)))
    check('L5  N, D are linear in (c,d), free of s, and both vanish at (c,d) = (1,-1)',
          Poly(N, c, d).total_degree() == 1 and Poly(D, c, d).total_degree() == 1
          and not N.has(s) and not D.has(s)
          and expand(N.subs({c: 1, d: -1})) == 0 and expand(D.subs({c: 1, d: -1})) == 0)

    # L3  main identity: for all U, V on J, chord pi(U) pi(V) is tangent to C_mu(U-V)
    den = 1 - eps * m * s1 ** 2 * s2 ** 2
    cW = c1 * c2 + eps * s1 * s2 * d1 * d2            # c(U-V) * den
    dW = d1 * d2 + m * s1 * s2 * c1 * c2              # d(U-V) * den
    NW = expand(N.subs({c: cW / den, d: dW / den}) * den)
    DW = expand(D.subs({c: cW / den, d: dW / den}) * den)
    Au, Bu, Cu = tangency(line_through((a * c1, b * s1), (a * c2, b * s2)))
    check('L3  chord pi(U) pi(V) is tangent to C_mu(U-V), for all U, V on J',
          zero_mod(Au * NW ** 2 + Bu * NW * DW + Cu * DW ** 2, J2, (c1, d1, c2, d2, s1, s2)))
    # L9  ... and its other root is mu(T-(U+V)) = mu at (s+, c+, -d+)   (used by Theorem C)
    cS = c1 * c2 - eps * s1 * s2 * d1 * d2             # c(U+V) * den
    dS = d1 * d2 - m * s1 * s2 * c1 * c2                # d(U+V) * den
    NS = expand(N.subs({c: cS / den, d: -dS / den}) * den)
    DS = expand(D.subs({c: cS / den, d: -dS / den}) * den)
    check('L9  the other member tangent to chord pi(U) pi(V) is C_mu(T-(U+V))',
          zero_mod(Au * NS ** 2 + Bu * NS * DS + Cu * DS ** 2, J2, (c1, d1, c2, d2, s1, s2)))

    # L4  the billiard step: pi(G) = B, chord AB tangent to C, and D(G) = 0 (mu(G) = infinity)
    sG, cG = 2 * t / (1 + eps * t ** 2), (1 - eps * t ** 2) / (1 + eps * t ** 2)
    Bp = (a * cG, b * sG)
    uu, vv, ww = Bp[1], a - Bp[0], a * Bp[1]
    lamG = cancel((A * uu ** 2 + B * vv ** 2 - ww ** 2) / (uu ** 2 + vv ** 2))
    mG = cancel(eps * (B - A) / (B - lamG))
    KG = a ** 2 + b ** 2 * (mG - eps)
    dG = cancel(-(a ** 2 * mG * (cG - 1)) / (eps * KG) - 1)      # solves D = 0
    check('L4  the point G with pi(G) = B and D(G) = 0 lies on J',
          cancel(cG ** 2 + eps * sG ** 2 - 1) == 0 and cancel(dG ** 2 + mG * sG ** 2 - 1) == 0)
    print(f'      lam(t) = {factor(lamG)},  m(t) = {factor(mG)},  d_G(t) = {factor(dG)}', flush=True)

    # L11 the converse: every W on J (with 1+d != 0) is the step G of a billiard with the same m,
    #     taking b^2 = -a^2 (m(c-1) + eps(1+d)) / (eps (m-eps)(1+d))   (needs b^2 to be a square)
    b2 = -a ** 2 * (m * (c - 1) + eps * (1 + d)) / (eps * (m - eps) * (1 + d))
    BB = eps * b2
    u2, v2, w2 = b2 * s ** 2, (a * (1 - c)) ** 2, a ** 2 * b2 * s ** 2
    lamW = (A * u2 + BB * v2 - w2) / (u2 + v2)
    check('L11 that billiard (start (a,0), second impact (a c, b s)) has state curve parameter m',
          zero_mod(eps * (BB - A) / (BB - lamW) - m, J1, (c, d, s)))
    # (D(W) = 0 holds by the choice of b^2, so G = W; the content is the check above.)
    check('L12 b^2 = -a^2 (c+d) / ((1+c)(m-eps)); with L7 this gives b^2 ~ -(m-eps)*delta(W) mod squares',
          zero_mod(b2 * (1 + c) * (m - eps) + a ** 2 * (c + d), J1, (c, d, s)))

    # L6  T - W = (s, c, -d) and 2T = O
    def add(U, V):
        (x1, y1, z1), (x2, y2, z2) = U, V
        q = 1 - eps * m * x1 ** 2 * x2 ** 2
        return tuple(cancel(z / q) for z in (x1 * y2 * z2 + x2 * y1 * z1,
                                             y1 * y2 - eps * x1 * x2 * z1 * z2,
                                             z1 * z2 - m * x1 * x2 * y1 * y2))
    check('L6  T + (s,c,d) = (-s,c,-d), so T - W = (s,c,-d); and T + T = O',
          add((0, 1, -1), (s, c, d)) == (-s, c, -d) and add((0, 1, -1), (0, 1, -1)) == (0, 1, 1))

    # L7  Weierstrass model and the type of C_mu(W)
    x = (1 + c) * (1 + d) / s ** 2
    y = (1 + c) * (1 + d) * (c + d) / s ** 3
    check('L7  x = (1+c)(1+d)/s^2, y = (1+c)(1+d)(c+d)/s^3 satisfy y^2 = x(x-eps)(x-m)',
          zero_mod(y ** 2 - x * (x - eps) * (x - m), J1, (c, d, s)))
    q0, q1 = e[0] + muW * cv[0], e[1] + muW * cv[1]
    check('L7  A*B*q0*q1 of C_mu(W) = (x(W) - eps) * (K s (1+d) / ((1+c) D))^2',
          zero_mod(A * B * q0 * q1 - (x - eps) * (K * s * (1 + d) / ((1 + c) * D)) ** 2, J1, (c, d, s)))

    # L8  when is C_mu(W) degenerate?  The q2 part is proved here; the q0*q1 part follows from L7
    #     (for s != 0 the factors 1+c, 1+d, D, K are non-zero and x(W) = eps only at s = 0).
    check('L8  N + D = eps*K*(c+d), so mu(W) = -1 (q2 = 0) iff c = -d, i.e. s = 0',
          expand(N + D - eps * K * (c + d)) == 0)
    check('L8  c = -d forces s = 0 on J:  c^2 - d^2 = (m - eps) s^2',
          zero_mod(c ** 2 - d ** 2 - (m - eps) * s ** 2, J1, (c, d, s)))

    # L13 (second half)  the caustic evaluated at an impact: decides whether its tangents are rational
    Cx = (a * c) ** 2 * cv[0] + (b * s) ** 2 * cv[1] - 1
    check('L13 caustic at pi(s,c): C(a c, b s) = lam (1 - m s^2) / (A - lam) on c^2 + eps s^2 = 1',
          zero_mod(Cx - lam * (1 - m * s ** 2) / (A - lam), [c ** 2 + eps * s ** 2 - 1], (c, s)))

    # L14  the other two 2-torsion points act as the centre and y-axis mirrors
    check('L14 (0,-1,1) + (s,c,d) = (-s,-c,d) and (0,-1,-1) + (s,c,d) = (s,-c,-d); both have order 2',
          add((0, -1, 1), (s, c, d)) == (-s, -c, d) and add((0, -1, -1), (s, c, d)) == (s, -c, -d)
          and add((0, -1, 1), (0, -1, 1)) == (0, 1, 1) and add((0, -1, -1), (0, -1, -1)) == (0, 1, 1))


def reflect(qx, qy, lx, ly, X0, X1):
    """conic_billiard.core.Conic.next_point(X0, X1), symbolically."""
    vx, vy = X1[0] - X0[0], X1[1] - X0[1]
    nx, ny = qx * X1[0] + lx / 2, qy * X1[1] + ly / 2
    sc = 2 / (nx * nx + ny * ny)
    h00, h01, h11 = 1 - sc * nx * nx, -sc * nx * ny, 1 - sc * ny * ny
    w0, w1 = h00 * vx + h01 * vy, h01 * vx + h11 * vy
    tau = -(2 * (qx * X1[0] * w0 + qy * X1[1] * w1) + lx * w0 + ly * w1) / (qx * w0 * w0 + qy * w1 * w1)
    return X1[0] + tau * w0, X1[1] + tau * w1


def run_degenerate() -> None:
    """Identities behind docs/security_dictionary.md that do not depend on eps."""
    print('\n=== degenerate boundaries and the tangent discriminant ===', flush=True)
    q0, q1, x, y, r, u, v = symbols('q0 q1 x y r u v')

    # L13 (first half)  tangent directions from X to q0 x^2 + q1 y^2 = 1
    Cx = q0 * x ** 2 + q1 * y ** 2 - 1
    form = lambda d0, d1: (q0 * x * d0 + q1 * y * d1) ** 2 - Cx * (q0 * d0 ** 2 + q1 * d1 ** 2)
    Af, Cf = form(1, 0), form(0, 1)
    Bf = (form(1, 1) - Af - Cf) / 2
    check('L13 the tangent-direction discriminant from X to q0 x^2 + q1 y^2 = 1 is q0 q1 C(X)',
          expand(Bf ** 2 - Af * Cf - q0 * q1 * Cx) == 0)

    # L15  circle: reflection at X1 sends X0 to its mirror image in the line O X1
    P = lambda w: (r * (1 - w ** 2) / (1 + w ** 2), 2 * r * w / (1 + w ** 2))
    X0, X1 = P(t1), P(t2)
    X2 = reflect(1 / r ** 2, 1 / r ** 2, 0, 0, X0, X1)
    dot, nn = X0[0] * X1[0] + X0[1] * X1[1], X1[0] ** 2 + X1[1] ** 2
    check('L15 circle: next impact = 2 (X0.X1)/(X1.X1) X1 - X0 (mirror of X0 in the line O X1)',
          all(cancel(X2[i] - (2 * dot / nn * X1[i] - X0[i])) == 0 for i in range(2)))

    # L16  parabola y = x^2: a fixed linear recurrence in the x-coordinate
    X2 = reflect(1, 0, 0, -1, (u, u ** 2), (v, v ** 2))
    k = (u - v) ** 2 / (1 + 4 * u * v)
    w = (2 + 4 * k) * v - u
    check('L16 parabola: next impact is (w, w^2) with w = (2 + 4k) v - u, k = (u-v)^2 / (1+4uv)',
          cancel(X2[0] - w) == 0 and cancel(X2[1] - w ** 2) == 0)
    check('L16 parabola: k is the same for the next chord, so the recurrence is fixed',
          cancel((v - w) ** 2 / (1 + 4 * v * w) - k) == 0)


if __name__ == '__main__':
    for eps in (1, -1):
        run(eps)
    run_degenerate()
    print('\nRESULT:', 'all identities hold' if not FAILED else f'{len(FAILED)} FAILED: {FAILED}', flush=True)
    sys.exit(1 if FAILED else 0)
